/* ------------------------------------------------------------------ */

/**
 * Generate professional listing content for a vehicle.
 *
 * Tries OpenAI GPT-4o-mini first (if OPENAI_API_KEY is set),
 * then falls back to template-based generation (zero tokens, zero cost).
 */
export async function generateListing(vehicle: Partial<Vehicle>): Promise<ListingContent> {
  // Strategy 1: OpenAI
  const aiResult = await generateWithOpenAI(vehicle);
  if (aiResult) return aiResult;

  // Strategy 2: Template (always available)
  return generateWithTemplate(vehicle);
}
